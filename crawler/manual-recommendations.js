// 获取推荐内容
export function getManualRecommendations(limit = 10) {
  return {
    articles: manualRecommendations.articles.slice(0, limit),
    videos: manualRecommendations.videos.slice(0, limit),
    lastUpdate: manualRecommendations.lastUpdate,
    nextUpdate: manualRecommendations.nextUpdate
  };
}

// 添加新的推荐
export function addRecommendation(item) {
  if (item.type === 'video') {
    manualRecommendations.videos.unshift(item);
  } else {
    manualRecommendations.articles.unshift(item);
  }
}

// 删除推荐
export function removeRecommendation(id) {
  const articleIndex = manualRecommendations.articles.findIndex(a => a.id === id);
  if (articleIndex !== -1) {
    manualRecommendations.articles.splice(articleIndex, 1);
    return true;
  }
  
  const videoIndex = manualRecommendations.videos.findIndex(v => v.id === id);
  if (videoIndex !== -1) {
    manualRecommendations.videos.splice(videoIndex, 1);
    return true;
  }
  
  return false;
}
